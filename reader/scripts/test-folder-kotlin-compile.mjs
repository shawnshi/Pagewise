import assert from 'node:assert/strict'
import { test } from 'node:test'
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs'
import { resolve, join } from 'node:path'
import { spawnSync } from 'node:child_process'

const home = process.env.USERPROFILE
const root = resolve(import.meta.dirname, '..')
function files(path, suffix) {
  return readdirSync(path, { recursive: true, withFileTypes: true }).filter(e => e.isFile() && e.name.endsWith(suffix)).map(e => join(e.parentPath, e.name))
}

test('full monitored-folder source compiles against installed Android, AndroidX and actual Tauri sources', { timeout: 90000 }, () => {
  const cache = resolve(home, '.gradle/caches')
  const modules = join(cache, 'modules-2/files-2.1')
  const compiler = files(join(modules, 'org.jetbrains.kotlin/kotlin-compiler-embeddable/2.0.21'), '.jar')
  const kotlin = ['org.jetbrains.kotlin/kotlin-stdlib', 'org.jetbrains.kotlin/kotlin-script-runtime',
    'org.jetbrains.kotlin/kotlin-reflect', 'org.jetbrains.intellij.deps/trove4j',
    'org.jetbrains.kotlinx/kotlinx-coroutines-core-jvm', 'org.jetbrains/annotations'].flatMap(p => files(join(modules, p), '.jar')).filter(p => !p.endsWith('-sources.jar'))
  const android = resolve(home, 'AppData/Local/Android/Sdk/platforms/android-36/android.jar')
  const androidx = [
    ...files(join(cache, '8.14.3/transforms'), '.jar').filter(p => p.endsWith('jars\\classes.jar') || p.endsWith('jars/classes.jar')),
    ...files(join(modules, 'androidx.lifecycle/lifecycle-common/2.5.1'), '.jar'),
  ]
  const jackson = ['com.fasterxml.jackson.core/jackson-annotations', 'com.fasterxml.jackson.core/jackson-core',
    'com.fasterxml.jackson.core/jackson-databind']
    .flatMap(p => files(join(modules, p), '.jar')).filter(p => !p.endsWith('-sources.jar'))
  const tauri = resolve(home, '.cargo/registry/src/index.crates.io-1949cf8c6b5b557f/tauri-2.11.5/mobile/android/src/main/java')
  const output = resolve(root, '../.cache/performance-20261019/kotlin-full')
  mkdirSync(output, { recursive: true })
  // This constant is normally generated by AGP; all Tauri API classes are real installed sources.
  const config = join(output, 'BuildConfig.kt')
  writeFileSync(config, 'package app.tauri\nobject BuildConfig { const val DEBUG = true }\n')
  const args = ['-no-stdlib', '-no-reflect', '-classpath', [android, ...androidx, ...kotlin, ...jackson].join(';'),
    '-d', join(output, 'classes'), config, ...files(tauri, '.kt'), join(root, 'src-tauri/android/MonitoredFolderPlugin.kt')]
  const argFile = join(output, 'compile.args')
  writeFileSync(argFile, args.map(arg => JSON.stringify(arg)).join('\n'))
  const command = ['-cp', [...compiler, ...kotlin].join(';'), 'org.jetbrains.kotlin.cli.jvm.K2JVMCompiler', '@' + argFile]
  writeFileSync(join(output, 'command.json'), JSON.stringify({ executable: 'java', args: command, tauri, android }, null, 2))
  const compile = spawnSync('java', command, { encoding: 'utf8', timeout: 75000 })
  writeFileSync(join(output, 'compile.log'), compile.stdout + compile.stderr)
  assert.equal(compile.status, 0, compile.error?.message ?? compile.stdout + compile.stderr)
  assert.ok(readFileSync(join(output, 'classes/io/pagewise/reader/MonitoredFolderPlugin.class')).byteLength > 0)
  console.log('Full plugin Kotlin compile passed; actual Tauri 2.11.5 sources + installed android-36/AndroidX; no Gradle or dependency writes.')
})
